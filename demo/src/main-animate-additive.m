#import <MulleUICore/MulleUICore.h>

#import <string.h>

//
// Shows how two animations of "frame" are mixed together using
// -setAnimationIsAdditive:. If set to YES, the previous layers animations
// are not removed during -commit. Also the animation do not just write an
// interpolated value from the start and end values, but instead read the
// current value and add the interpolate change.
//
void  setupAnimation( UIWindow *window, CALayer *layer)
{
   CATransaction      *ta;
   CAAnimationGroup   *group;

   ta = [CATransaction object];
   [ta begin];
   {
      [ta setAnimationCurve:UIViewAnimationCurveEaseInOut];
      [ta setAnimationDelay:2];
      [ta setAnimationDuration:2];
      [ta setAnimationRepeatCount:20];
      [ta setAnimationAutoreverses:YES];
      [ta setAnimationIsAdditive:YES];

      [layer setFrame:CGRectMake( 600, 100, 100, 100)];
   }
   group = [ta commit];
   [[window postLayoutAnimator] addAnimation:group];

   [ta begin];
   {
      [ta setAnimationCurve:UIViewAnimationCurveEaseInOut];
      [ta setAnimationDelay:2.5];
      [ta setAnimationDuration:2];
      [ta setAnimationRepeatCount:20];
      [ta setAnimationAutoreverses:YES];
      [ta setAnimationIsAdditive:YES];

      [layer setFrame:CGRectMake( 100, 400, 100, 100)];
   }
   group = [ta commit];
   [[window postLayoutAnimator] addAnimation:group];
}


void   setupSceneAndAnimation( UIWindow *window)
{
   CALayer   *layer;

   layer = [CALayer layerWithFrame:CGRectMake( 100, 100, 100, 100)];
   [layer setBackgroundColor:CGColorMakeWithUnsignedInteger( 0xFF0000FF)];
   [[window contentPlane] addLayer:layer];

   // UIView -> CAAnimation
   setupAnimation( window, layer);
}


int   main( int argc, char *argv[])
{
   UIWindow        *window;
   UIApplication   *app;
   /*
    * window and app
    */
   app    = [UIApplication sharedInstance];
   window = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 800.0, 600.0)];
   assert( window);

   [window setBackgroundColor:CGColorMakeRGBA( 1.0, 1.0, 1.0, 1.0)];

   setupSceneAndAnimation( window);

   [window dump];

   [app addWindow:window];
   [window renderLoop];

   return( [app terminate]);
}


