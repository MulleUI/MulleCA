#import <MulleCA/MulleCA.h>

#import <stdio.h>


@interface Foo : NSObject

@property( assign) CGFloat   v;

@end

@implementation Foo

- (void) setV:(CGFloat) v
{
   printf( "%.1f", v);
}

@end


int   main( int argc, char *argv[])
{
   Foo                              *foo;
   CABasicAnimation                 *animation;
   NSInteger                        i;
   mulle_absolutetime_t             now;
   struct CABasicAnimationOptions   options;
   NSUInteger                       state;

   foo       = [Foo object];

   // basic animation duration by default is 1
   options   = CABasicAnimationOptionsMakeLinear( mulle_relativetimerange_make( 0.0, 1.0), 2.0, NO);
   fprintf( stderr, "%s\n", CABasicAnimationOptionsUTF8String( &options));

   animation = [[[CABasicAnimation alloc] initWithProperty:MulleObjCInstanceSearchProperty( foo, @selector( v))
                                         startFloatValue:-10.0
                                           endFloatValue:+10.0
                                                   options:&options] autorelease];

   for( now = 0.0, i = 0;; i++, now += 1 / 10.0)
   {
      printf( "%td: %g ", i, now);
      state = [animation animateObject:foo
                          absoluteTime:now
                         animationRate:1 / 10.0];
      printf( "\n");
      if( state == CAAnimationReturnStateDone)
         break;
   }

   return( 0);
}


