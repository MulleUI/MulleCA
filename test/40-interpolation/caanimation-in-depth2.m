#import <MulleCA/MulleCA.h>

#import <stdio.h>


@interface Foo : NSObject

@property( assign) CGFloat   f;

@property( assign) NSInteger outputStep;  // just for printing

@end


@implementation Foo

- (void) setF:(CGFloat) f
{
   char     *abc = "ABC";

   _f = f;  // don't need to store it for non additive
   printf( "%td: %.3f '%c'\n", _outputStep, f, abc[ (int) round( f * 2.0f)]);
}

@end



#define DURATION        3.0
#define REPEATS         2.0
#define ANIMATION_RATE  (1.0 / 2.0)


int   main( int argc, char *argv[])
{
   Foo                              *foo;
   CABasicAnimation                 *animation;
   NSInteger                        i;
   struct CABasicAnimationOptions   options;
   struct _mulle_objc_property      *property;
   mulle_relativetime_t             elapsed;
   foo       = [Foo instance];
   // though this looks a little wordy, its easier to figure out
   // what what is
   options   = (struct CABasicAnimationOptions)
               {
                  .base = (struct CAAnimationOptions)
                          {
                              .timeRange   = mulle_relativetimerange_make( 0, DURATION),
                              .offset      = 0.0,
                              .repeatCount = REPEATS,
                              .bits        = CAAnimationRateCorrect
                          },
                  .curve = CAAnimationCurveLinear,
                  .tween = NULL
               };

   property  = MulleObjCInstanceSearchProperty( foo, @selector( f));
   animation = [[[CABasicAnimation alloc] initWithProperty:property
                                           startFloatValue:0
                                             endFloatValue:1
                                                   options:&options] autorelease];
   i = 0;
   for( elapsed = 0.0; elapsed < REPEATS * DURATION; elapsed += ANIMATION_RATE)
   {
      [foo setOutputStep:i];
      [animation animateObject:foo
                  absoluteTime:elapsed
                 animationRate:ANIMATION_RATE];
      ++i;
   }

   return( 0);
}


