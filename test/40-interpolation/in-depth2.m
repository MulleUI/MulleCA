#include <stdio.h>
#include <math.h>


#define DURATION        3.0
#define REPEATS         2.0
#define ANIMATION_RATE  (1.0 / 2.0)

int   main( int argc, char *argv[])
{
   double        corrected;
   double        elapsed;
   double        maxValue;
   double        midpoint;
   double        minValue;
   double        step;
   double        value;
   char          *abc = "ABC";
   unsigned int  i;

   i = 0;
   for( elapsed = 0.0; elapsed < REPEATS * DURATION; elapsed += ANIMATION_RATE)
   {
      minValue = ANIMATION_RATE / 2 / DURATION; // this is 0.125
      maxValue = 1.0 - minValue;               // this is 0.875

      midpoint = elapsed + (ANIMATION_RATE / 2);
      value    = fmod( midpoint / DURATION, 1.0);
      corrected = value + ((value - 0.5) / (maxValue - 0.5)) * minValue;
      if( corrected < minValue)
         corrected = 0.0;
      if( corrected > maxValue)
         corrected = 1.0;

      printf( "%u %.2f %.2f %.3f %g '%c'\n",
                i,
                elapsed, midpoint, value, corrected,
                abc[ (int) round( corrected * 2.0f)]);
      ++i;
   }
   return( 0);
}


