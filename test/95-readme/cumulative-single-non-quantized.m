#import <MulleCA/MulleCA.h>

#import <stdio.h>


@interface Foo : NSObject

@property( assign) NSInteger   x;

@end


@implementation Foo

- (void) setX:(NSInteger) x
{
   _x = x;
   printf( "%td\n", x);
}

@end


int   main( int argc, char *argv[])
{
   Foo                              *foo;
   CABasicAnimation                 *animation;
   NSInteger                        i;
   struct CABasicAnimationOptions   options;
   struct _mulle_objc_property      *property;

   foo = [Foo instance];
   [foo setX:10];       // initial value, don't care for plain

   options = CABasicAnimationOptionsMakeCurve( mulle_relativetimerange_make( 0, 4),
                                               CAAnimationCurveLinear,
                                               2.0,
                                               NO);
   CABasicAnimationOptionsSetBit( &options, CAAnimationAdditive|CAAnimationCumulative);
   fprintf( stderr, "%s\n", CABasicAnimationOptionsUTF8String( &options));

   property  = MulleObjCInstanceSearchProperty( foo, @selector( x));
   animation = [[[CABasicAnimation alloc] initWithProperty:property
                                         startIntegerValue:0
                                           endIntegerValue:20
                                                   options:&options] autorelease];

   for( i = 0; i < 9; i++) // need one more step!
   {
      printf( "%ld: ", i);
      [animation animateObject:foo
                  absoluteTime:i * 1.0  // want values from 0 to 1
                 animationRate:0.0];
   }

   return( 0);
}


